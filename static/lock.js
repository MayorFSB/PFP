// Локон PFP — точка входа.
//
// Вся сцена разложена по модулям в static/3d/. Этот файл существует только
// чтобы запустить сборку и не менять HTML: порядок импортов задаёт порядок
// инициализации, а побочные эффекты модулей (создание меша волос, систем
// частиц, чтение DOM-инструментов) выполняются при загрузке.
//
//   3d/config.js     все числа: TL, PHASE, константы. Без побочных эффектов.
//   3d/core.js       renderer/scene/camera, проекция world→CSS, мышь, GLSL-чеки
//   3d/hair.js       геометрия локона + шейдеры + permanent uniforms
//   3d/particles.js  фабрика makePoints и все системы частиц
//   3d/tools.js      ножницы, утюжок, баллончик (DOM-оверлеи)
//   3d/phases/*      по модулю на этап; меняют состояние волос
//   3d/director.js   скролл → p, обход фаз, governor качества
//   3d/main.js       bootstrap, RAF-цикл, resize, отладка
//
// Порядок важен: hair должен создаться до частиц (они занимают его
// uniforms), tools — после частиц (ставят им uSnip/uIronFocus).
//
// Ключевые техники (референсы — мокрые нити с каплями и золотое плетение):
//  • Ширина ровно 2–3 px независимо от глубины: линия расширяется в clip-space
//    (gl.lineWidth в WebGL зажат в 1px — использовать нельзя).
//  • Kajiya-Kay: два анизотропных лепестка вдоль касательной — продольный блик
//    мокрых волос и шёлковистость сухих.
//  • Marschner: R (белый, exp 150) + TRT (окрашен абсорбцией, exp 16).
//  • Затенение по глубине вместо сортировки: передние нити ярче, задние темнее,
//    поэтому плетение читается как «поверх/под» без depth-sort.
//  • Меланин по Chiang 2016: σ_a = eumelanin·mel + pheomelanin·redness.
//
// Порядок нитей в буфере — низко-дискриминантная последовательность, поэтому
// усечение drawRange даёт равномерное прореживание, а не отвалившийся хвост.
